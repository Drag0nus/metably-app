"""Checks each diary bread-unit amount against USDA carbohydrates and writes diary-check.md.

The diary says each listed amount is 1 bread unit (10-12 g carbohydrate). USDA values differ by
variety and preparation, so this is a report for review, not a pass/fail gate.
"""
import json, re
catalog = json.load(open('foods.json', encoding='utf-8'))
by_uk = {f['nameUK']: f for f in catalog['foods']}
rows = []
for line in open('diary-portions.tsv', encoding='utf-8'):
    if not line.strip() or line.startswith('#'): continue
    food_uk, _en, uk, _grams, page, wording = line.rstrip('\n').split('\t')
    m = re.search(r'([\d.,–-]+)\s*г$', wording)
    if not m: continue
    amount = m.group(1).replace(',', '.')
    if '–' in amount or '-' in amount:
        lo, hi = re.split('[–-]', amount); amount = (float(lo) + float(hi)) / 2
    grams = float(amount)
    per = by_uk[food_uk]['per100g']
    carbs = per['carbohydrate'] * grams / 100
    net = (per['carbohydrate'] - per.get('fiber', 0)) * grams / 100 if 'fiber' in per else None
    rows.append((page, food_uk, wording, grams, carbs, net))
out = ['# Diary bread-unit amounts against USDA carbohydrates', '',
       'Generated by `diary_check.py`. The diary counts each amount as 1 bread unit (10-12 g',
       'carbohydrate). The app always computes from USDA grams, never from this table.',
       'USDA "carbohydrate, by difference" includes fibre; bread-unit tables usually count',
       'carbohydrate without fibre, so both are shown.', '',
       '| Page | Food | Diary amount | g | USDA carbs, g | without fibre, g | Within 10-12 g |',
       '|---|---|---|---|---|---|---|']
def within(r):
    value = r[5] if r[5] is not None else r[4]
    return 9.5 <= value <= 12.5
for r in rows:
    page, food, wording, grams, carbs, net = r
    net_text = f'{net:.1f}' if net is not None else 'n/a'
    out.append(f'| {page} | {food} | {wording} | {grams:g} | {carbs:.1f} | {net_text} | {"yes" if within(r) else "no"} |')
count = sum(1 for r in rows if within(r))
out += ['', f'{count} of {len(rows)} diary amounts give 10-12 g carbohydrate without fibre (±0.5 g) by USDA values.',
        'The rest show how much a fixed exchange table can differ from measured food data.', '']
within = count
open('diary-check.md', 'w', encoding='utf-8').write('\n'.join(out))
print(within, len(rows))
